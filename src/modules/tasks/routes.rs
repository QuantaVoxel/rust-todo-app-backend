use salvo::Router;

use crate::core::middleware::auth_middleware;
use crate::modules::tasks::handlers;

pub fn routes() -> Router {
    Router::new()
        .hoop(auth_middleware)
        .push(
            Router::with_path("tasks")
                .get(handlers::list_tasks)
                .post(handlers::create_task)
                .push(
                    Router::with_path("{task_id}")
                        .get(handlers::get_task)
                        .patch(handlers::update_task)
                        .delete(handlers::delete_task)
                        .push(Router::with_path("archive").post(handlers::archive_task))
                        .push(Router::with_path("unarchive").post(handlers::unarchive_task))
                        .push(Router::with_path("progress").put(handlers::update_progress))
                        .push(
                            Router::with_path("subtasks")
                                .get(handlers::list_subtasks)
                                .post(handlers::create_subtask),
                        )
                        .push(
                            Router::with_path("notes")
                                .get(handlers::list_notes)
                                .post(handlers::create_note),
                        )
                        .push(
                            Router::with_path("comments")
                                .get(handlers::list_comments)
                                .post(handlers::create_comment),
                        )
                        .push(
                            Router::with_path("attachments")
                                .get(handlers::list_attachments)
                                .post(handlers::upload_attachment),
                        )
                        .push(
                            Router::with_path("reminders")
                                .get(handlers::list_reminders)
                                .post(handlers::create_reminder),
                        )
                        .push(
                            Router::with_path("recurrence")
                                .get(handlers::get_recurrence)
                                .put(handlers::upsert_recurrence)
                                .delete(handlers::delete_recurrence),
                        )
                        .push(
                            Router::with_path("locations")
                                .get(handlers::list_task_locations)
                                .push(
                                    Router::with_path("{location_id}")
                                        .put(handlers::link_task_location)
                                        .delete(handlers::unlink_task_location),
                                ),
                        )
                        .push(
                            Router::with_path("shares")
                                .get(handlers::list_shares)
                                .push(
                                    Router::with_path("{user_id}")
                                        .put(handlers::upsert_share)
                                        .delete(handlers::delete_share),
                                ),
                        )
                        .push(Router::with_path("votes").get(handlers::get_votes))
                        .push(
                            Router::with_path("vote")
                                .put(handlers::upsert_vote)
                                .delete(handlers::delete_vote),
                        )
                        .push(
                            Router::with_path("history")
                                .push(Router::with_path("status").get(handlers::get_status_history))
                                .push(Router::with_path("priority").get(handlers::get_priority_history))
                                .push(Router::with_path("labels").get(handlers::get_labels_history)),
                        )
                        .push(
                            Router::with_path("integrations")
                                .get(handlers::list_integrations)
                                .post(handlers::create_integration),
                        )
                        .push(
                            Router::with_path("tags/{tag_id}")
                                .put(handlers::attach_task_tag)
                                .delete(handlers::detach_task_tag),
                        )
                        .push(
                            Router::with_path("categories/{category_id}")
                                .put(handlers::attach_task_category)
                                .delete(handlers::detach_task_category),
                        )
                        .push(
                            Router::with_path("labels/{label_id}")
                                .put(handlers::attach_task_label)
                                .delete(handlers::detach_task_label),
                        ),
                ),
        )
        .push(
            Router::with_path("subtasks/{subtask_id}")
                .patch(handlers::update_subtask)
                .delete(handlers::delete_subtask),
        )
        .push(
            Router::with_path("notes/{note_id}")
                .patch(handlers::update_note)
                .delete(handlers::delete_note)
                .push(Router::with_path("history").get(handlers::get_note_history)),
        )
        .push(
            Router::with_path("comments/{comment_id}")
                .patch(handlers::update_comment)
                .delete(handlers::delete_comment),
        )
        .push(
            Router::with_path("attachments/{attachment_id}")
                .delete(handlers::delete_attachment),
        )
        .push(
            Router::with_path("reminders/{reminder_id}")
                .patch(handlers::update_reminder)
                .delete(handlers::delete_reminder),
        )
        .push(
            Router::with_path("locations")
                .get(handlers::list_locations)
                .post(handlers::create_location),
        )
        .push(
            Router::with_path("integrations/{integration_id}")
                .delete(handlers::delete_integration),
        )
}
